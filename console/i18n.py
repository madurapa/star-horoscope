def tr(text, locale):
    """Localize a title/key; unknown locales and strings pass through."""
    if locale in ("si", "ta"):
        row = STRINGS.get(text)
        if row:
            return row[0] if locale == "si" else row[1]
    return text

def trv(text, locale, table):
    """Translate a report value via a VALUES table; unknown locales,
    tables, and keys pass through (English fallback, like the core)."""
    if locale in ("si", "ta"):
        row = VALUES.get(table, {}).get(text)
        if row:
            return row[1] if locale == "si" else row[2]
    return text

def tr_tithi(text, locale):
    """Translate the limb inside a full tithi string, preserving the
    Pura-/Ava- prefix, spacing, and day number. Unparseable strings
    (e.g. Amaawaka-15) pass through."""
    if locale in ("si", "ta"):
        for limb, row in VALUES.get("limbs", {}).items():
            if limb and limb in text:
                return text.replace(limb, row[1] if locale == "si" else row[2], 1)
    return text

